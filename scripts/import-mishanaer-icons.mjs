import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/icons",
);
const manifest = JSON.parse(
  await fs.readFile(path.join(root, "source-manifest.json"), "utf8"),
);
const icons = {};
const allowed = new Set([
  "d",
  "fill",
  "fill-rule",
  "clip-rule",
  "opacity",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin",
]);

function pathsFrom(source) {
  const svg = source
    .trim()
    .match(/^<svg\s+[^>]*viewBox="0 0 24 24"[^>]*>([\s\S]*)<\/svg>$/);
  if (!svg) throw new Error("Expected a 24px SVG");
  // This catalogue uses a full-viewBox clip on code.svg. The outer SVG viewport
  // supplies the same clip without document-global IDs shared by every instance.
  let body = svg[1];
  const boundsClip =
    '<defs><clipPath id="a"><path fill="currentColor" d="M0 0h24v24H0z"/></clipPath></defs>';
  if (
    body.startsWith('<g clip-path="url(#a)">') &&
    body.endsWith(`</g>${boundsClip}`)
  )
    body = body.slice(
      '<g clip-path="url(#a)">'.length,
      -`</g>${boundsClip}`.length,
    );
  const paths = [...body.matchAll(/<path\s+([^>]*)\/>/g)];
  if (!paths.length || body.replace(/<path\s+[^>]*\/>/g, "").trim())
    throw new Error("Only static path geometry is accepted");
  return paths.map(([, attributes]) => {
    const entries = [...attributes.matchAll(/([\w-]+)="([^"]*)"/g)];
    if (
      attributes.replace(/([\w-]+)="([^"]*)"/g, "").trim() ||
      entries.some(([, key]) => !allowed.has(key))
    )
      throw new Error("Unexpected SVG path attribute");
    return Object.fromEntries(
      entries.map(([, key, value]) => [
        key.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()),
        value,
      ]),
    );
  });
}

const jobs = ["stroke", "filled"].flatMap((variant) =>
  manifest[variant].map((icon) => ({ ...icon, variant })),
);
for (let index = 0; index < jobs.length; index += 8) {
  const results = await Promise.allSettled(
    jobs.slice(index, index + 8).map(async ({ name, url, variant }) => {
      const sourceUrl = new URL(url);
      if (
        sourceUrl.origin !== manifest.source.replace(/\/$/, "") ||
        !sourceUrl.pathname.startsWith("/icons/round/")
      )
        throw new Error("Unexpected icon source");
      const directory = path.join(root, "assets", variant);
      let svg = await fs
        .readFile(path.join(directory, `${name}.svg`), "utf8")
        .catch(() => null);
      if (!svg) {
        const response = await fetch(sourceUrl, {
          redirect: "error",
          signal: AbortSignal.timeout(20000),
        });
        if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
        svg = await response.text();
      }
      let shapes;
      try {
        shapes = pathsFrom(svg);
      } catch (error) {
        throw new Error(
          `${variant}/${name}: ${error.message}\n${svg.slice(0, 1800)}`,
        );
      }
      icons[name] ||= {};
      icons[name][variant] = shapes;
      await fs.mkdir(directory, { recursive: true });
      await fs.writeFile(path.join(directory, `${name}.svg`), svg);
    }),
  );
  const failures = results.filter((result) => result.status === "rejected");
  if (failures.length)
    throw new AggregateError(failures.map((result) => result.reason));
}
// Documented local adaptations keep their catalogue originals above. Reading
// their SVGs here makes regeneration preserve the adapted UI geometry.
for (const { name, basedOn } of manifest.derivations || []) {
  if (!/^[a-z0-9-]+$/.test(name) || !icons[basedOn] || icons[name])
    throw new Error(`Invalid icon derivation: ${name}`);
  icons[name] = {};
  for (const variant of ["stroke", "filled"])
    icons[name][variant] = pathsFrom(
      await fs.readFile(path.join(root, "assets", variant, `${name}.svg`), "utf8"),
    );
}
for (const name of new Set(Object.values(manifest.mapping))) {
  if (!icons[name]?.stroke || !icons[name]?.filled)
    throw new Error(`Missing pair: ${name}`);
}
const ordered = Object.fromEntries(
  Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)),
);
await fs.writeFile(
  path.join(root, "geometry.ts"),
  `// Round SVG geometry from ${manifest.source}\n// Generated by scripts/import-mishanaer-icons.mjs. Source SVGs and documented adaptations are in assets/.\nexport const geometry = ${JSON.stringify(ordered, null, 2)} as const;\n`,
);
await fs.writeFile(
  path.join(root, "index.ts"),
  `import { createIcon } from "./Icon";\n\n${Object.entries(manifest.mapping)
    .map(
      ([name, source]) =>
        `export const ${name} = createIcon(${JSON.stringify(source)});`,
    )
    .join("\n")}\n`,
);
console.log(
  `Generated ${Object.keys(ordered).length} Round icon pairs (${jobs.length} catalogue SVGs, ${manifest.derivations?.length || 0} documented adaptations).`,
);
